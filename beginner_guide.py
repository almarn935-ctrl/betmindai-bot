class BeginnerGuide:

    @staticmethod
    def get_topics_keyboard():
        from telegram import KeyboardButton, ReplyKeyboardMarkup
        rows = []
        topics = list(TOPICS.keys())
        for i in range(0, len(topics), 2):
            pair = topics[i:i+2]
            rows.append([KeyboardButton(t) for t in pair])
        rows.append([KeyboardButton("🎲 Случайный совет"), KeyboardButton("❌ Закрыть гид")])
        return ReplyKeyboardMarkup(rows, resize_keyboard=True)

    @staticmethod
    def get_lesson(topic_name: str) -> str:
        topic_key = TOPICS.get(topic_name)
        if not topic_key:
            return "❌ Тема не найдена."
        lesson = LESSONS.get(topic_key)
        if not lesson:
            return "❌ Урок не найден."
        return lesson['text'] + f"\n\n💡 *Совет:* _{lesson['tip']}_"

    @staticmethod
    def get_random_tip() -> str:
        import random
        return random.choice(QUICK_TIPS)

    @staticmethod
    def get_personal_advice(stats: dict) -> str:
        """Персональные советы на основе статистики пользователя"""
        if stats['total_bets'] == 0:
            return (
                "🎓 *Персональные рекомендации*\n\n"
                "У тебя ещё нет ставок. Вот с чего начать:\n\n"
                "1️⃣ Определи банкрол — сумму которую не жалко потерять\n"
                "2️⃣ Выбери 1-2 лиги которые хорошо знаешь\n"
                "3️⃣ Ставь не более 2% банкрола на одно событие\n"
                "4️⃣ Записывай все ставки (бот делает это автоматически)\n"
                "5️⃣ Анализируй результаты через 50+ ставок"
            )

        lines = ["🎓 *Персональные рекомендации*\n"]

        # Анализ winrate
        wr = stats.get('winrate', 0)
        roi = stats.get('roi', 0)
        avg_odds = stats.get('avg_odds', 2.0)
        worst_streak = stats.get('worst_streak', 0)

        # Точка безубыточности
        breakeven = (1 / avg_odds * 100) if avg_odds > 0 else 50

        if wr < breakeven:
            lines.append(
                f"⚠️ *Внимание:* твой winrate {wr:.1f}% ниже точки безубыточности "
                f"({breakeven:.1f}% при среднем кэфе {avg_odds:.2f}).\n"
                "Рекомендую:\n"
                "• Снизить средний кэф ставок\n"
                "• Делать более тщательный анализ перед ставкой\n"
                "• Прочитать раздел «Как выбирать матчи»\n"
            )
        elif roi > 10:
            lines.append(
                f"🌟 *Отличные результаты!* ROI {roi:+.1f}% — профессиональный уровень.\n"
                "Совет: не увеличивай размер ставок резко, "
                "дай статистике накопиться до 200+ ставок.\n"
            )
        elif roi > 0:
            lines.append(
                f"✅ *Ты в плюсе!* ROI {roi:+.1f}%.\n"
                "Продолжай в том же духе и фокусируйся на value bet.\n"
            )
        else:
            lines.append(
                f"📉 *ROI {roi:+.1f}%.* Пока в минусе, но это нормально для начала.\n"
                "Главное — анализировать ошибки и не гнаться за отыгрышем.\n"
            )

        # Совет по сериям
        if worst_streak >= 5:
            lines.append(
                f"⚠️ У тебя была серия *{worst_streak} поражений подряд*.\n"
                "При повторении обязательно возьми паузу и перечитай "
                "раздел «Психология беттора».\n"
            )

        # Совет по количеству ставок
        total = stats.get('total_bets', 0)
        if total < 50:
            lines.append(
                f"📊 У тебя *{total} ставок* — ещё мало для достоверной статистики.\n"
                "Нужно минимум 100 ставок чтобы оценить реальный уровень.\n"
            )

        # Совет по кэфам
        if avg_odds > 4.0:
            lines.append(
                "🎯 Твой средний кэф очень высокий — ты играешь в зону риска.\n"
                "Попробуй снизить средний кэф до 1.7-2.5 для более стабильных результатов.\n"
            )
        elif avg_odds < 1.5:
            lines.append(
                "📐 Твой средний кэф очень низкий.\n"
                "При кэфе 1.4 нужен winrate 71%+ для прибыли — это очень сложно.\n"
            )

        lines.append("📖 Изучи разделы гида для новичков — там много полезного!")
        return "\n".join(lines)

    @staticmethod
    def is_topic(text: str) -> bool:
        return text in TOPICS or text in ("🎲 Случайный совет", "❌ Закрыть гид")

    @staticmethod
    def all_topic_names() -> set:
        return set(TOPICS.keys())
